/**
 * Crop requirement envelopes, in the style of the FAO EcoCrop database
 * (https://gaez.fao.org/pages/ecocrop) with FAO Irrigation & Drainage Paper 33
 * / 56 for season water demand and Maas & Hoffman for the salinity thresholds.
 *
 * These are INDICATIVE ENVELOPES for a species, not local trial data. They say
 * "tomato is happy between 20 and 27 °C", not "your neighbour got 80 t/ha". A
 * variety bred for your valley will beat these numbers, and a bad year will
 * miss them — treat a match as a shortlist, never as a guarantee.
 *
 * The table is bundled rather than fetched on purpose: the crop matcher has to
 * work on a phone with no signal standing in the middle of a field.
 *
 * `tempAbsC[0]` follows the EcoCrop convention: it is the temperature that
 * KILLS the crop, not the one it stops growing at. For the perennials that
 * matters — an olive at -7 °C is a dead tree, not a slow one — and the matcher
 * reads it that way when it checks a site's winter.
 *
 * For an ANNUAL the two coincide: a crop that dies at 10 °C also stops growing
 * there, so `tempAbsC[0]` doubles as its growth floor. For a PERENNIAL they are
 * ten to twenty degrees apart, which is why every perennial below carries an
 * explicit `tempGrowMinC`. Without it a grapevine scores on a band running down
 * to -15 °C and comes out "excellent" in Iceland. Any perennial added here MUST
 * set it; the matcher's fallback of `tempOptC[0] - 5` is a safety net, not a
 * default worth relying on.
 *
 * `family` uses the accepted botanical family. The rotation groups a farmer
 * actually thinks about — Solanaceae, Poaceae, Fabaceae, Cucurbitaceae,
 * Amaryllidaceae, Brassicaceae — cover most of the table; the handful of
 * one-off tree and oilseed families are spelled out honestly instead of being
 * forced into a group they do not belong to.
 */

import type { CropCategory, TextureClass } from "@/types/land"

export interface CropEnvelope {
  id: string
  name: string
  /** Botanical family, for rotation advice. */
  family: string
  category: CropCategory
  /** Optimal mean-temperature range for growth, °C. */
  tempOptC: [number, number]
  /**
   * Absolute survivable mean-temperature range, °C. The LOW end is the killing
   * temperature — see the file header. For an annual it is also the growth
   * floor; for a perennial it is not, and `tempGrowMinC` carries that instead.
   */
  tempAbsC: [number, number]
  /**
   * Mean temperature below which the crop makes no growth, °C. Set on every
   * perennial, where it sits far above the kill temperature in `tempAbsC[0]`;
   * omitted on annuals, where the two are the same number.
   */
  tempGrowMinC?: number
  /** Optimal annual/season rainfall, mm. */
  rainOptMm: [number, number]
  rainAbsMm: [number, number]
  phOpt: [number, number]
  phAbs: [number, number]
  /** Texture classes the crop does well on. */
  textures: TextureClass[]
  cycleDays: number
  /** Season water requirement, mm. */
  waterNeedMm: number
  /** true when a single frost ends the crop. */
  frostSensitive: boolean
  /** Salt tolerance, dS/m threshold; used later. */
  salinityToleranceDsM: number
  /** One line a farmer would find useful. */
  note: string
}

