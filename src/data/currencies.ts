/**
 * Alpha-2 → currency code, forgiving about case and whitespace because the
 * code arrives from a third-party geocoder. Null in → null out, unknown →
 * null: callers treat null as "show USD", never as an error.
 */
export function currencyOf(iso2: string | null): string | null {
  if (!iso2) return null
  return COUNTRY_CURRENCY[iso2.trim().toUpperCase()] ?? null
}
